c1 = 7
c2 = 4
c3 = 10

# ==

if c1 == c3 or not c2 == c3:
    print("Cumple")

# !=

if c1 != c3 or not c2 != c3:
    print("Es igual")

# >

if c1 > c3 or not c2 > c3:
    print("No cumple")

# <

if c1 < c3 or not c2 < c3:
    print("No cumple")

# >=

if c1 >= c3 or not c2 >= c3:
    print("No cumple")

# <=

if c1 <= c3 or not c2 <= c3:
    print("No cumple")