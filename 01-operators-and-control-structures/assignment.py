c1 = 7
c2 = 4
c3 = 10

# Suma

c1 += 3
c2 += 6
c3 += 0

# Resta

c1 -= 4
c2 -= 1
c3 -= 7

# Multiplicación

c1 *= 3
c2 *= 6
c3 *= 0

# División

c1 /= 3
c2 /= 6
c3 /= 1

# División entera

c1 //= 3
c2 //= 6
c3 //= 1

# Módulo

c1 %= 3
c2 %= 6
c3 %= 1

# Potencia

c1 **= 3
c2 **= 6
c3 **= 1


print(c1, c2, c3)